"""Generate build/OTACandidate.gen.m: embed the pinned OTA candidate descriptor
as C byte arrays so the addon dylib carries exactly the reviewed JSON bytes.
The candidate JSON is the single source of truth shared with
watch-remote/flash_check.py and the Android assets. Fail-closed: any
structural problem aborts the build.

Usage: python3 gen_otacandidate.py <candidate.json> <output.gen.m>
"""
import json
import sys
from pathlib import Path


def main():
    src, out = map(Path, sys.argv[1:3])
    raw = src.read_bytes()
    doc = json.loads(raw.decode('utf-8'))
    if doc.get('schema') != 1:
        raise SystemExit('Unsupported candidate schema')
    for key in ('codeName', 'confirmToken', 'baseVersion', 'zip', 'otaSize',
                'ap', 'apBudgetBytes', 'manifest', 'stockAPSHA256', 'payloadPins'):
        if key not in doc:
            raise SystemExit('Candidate missing ' + key)
    pins = doc['payloadPins']
    names = [p.get('name') for p in pins]
    if len(names) != len(set(names)) or not names:
        raise SystemExit('Duplicate or empty pin names')
    body = ','.join(str(b) for b in raw)
    out.write_text(
        '/* Generated by gen_otacandidate.py from %s -- do not edit. */\n'
        '#import <Foundation/Foundation.h>\n'
        'const unsigned char TIOOTACandidateJSON[]={%s};\n'
        'const unsigned int TIOOTACandidateJSONLength=%d;\n'
        % (src.name, body, len(raw)), encoding='utf-8')
    print('embedded candidate %s (%d bytes) -> %s' % (doc['codeName'], len(raw), out))


if __name__ == '__main__':
    main()
